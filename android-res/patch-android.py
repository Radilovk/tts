#!/usr/bin/env python3
"""
Patch the Android project generated by `npx cap add android` for Разказвач.

- Native code: MainActivity (keeps the WebView alive while reading),
  RazkazvachPlugin (device voices, playback service control, shared files),
  ReaderService (foreground media-playback service).
- Manifest: permissions, the service, TTS engine visibility (<queries>),
  "Share" / "Open with" intent filters for books.
- Gradle: version, fixed signing key, androidx.media.
- Launcher icons and window colours.
Idempotent: running it twice leaves the project unchanged.
"""

import re
import shutil
from pathlib import Path

APP = Path("android/app")
SRC = APP / "src/main"
PKG_DIR = SRC / "java/com/biocode/razkazvach"
RES = SRC / "res"
MANIFEST = SRC / "AndroidManifest.xml"

# ---- native sources and resources
PKG_DIR.mkdir(parents=True, exist_ok=True)
for f in Path("android-res/java/com/biocode/razkazvach").glob("*.java"):
    shutil.copy(f, PKG_DIR / f.name)
shutil.copytree("android-res/res", RES, dirs_exist_ok=True)

# ---- manifest
text = MANIFEST.read_text(encoding="utf-8")

permissions = [
    "android.permission.INTERNET",
    "android.permission.WAKE_LOCK",
    "android.permission.FOREGROUND_SERVICE",
    "android.permission.FOREGROUND_SERVICE_MEDIA_PLAYBACK",
    "android.permission.POST_NOTIFICATIONS",
]
for p in permissions:
    line = f'<uses-permission android:name="{p}" />'
    if line not in text:
        text = text.replace("<application", f"{line}\n    <application", 1)

if "android.intent.action.TTS_SERVICE" not in text:
    text = text.replace("<application", """<queries>
        <intent><action android:name="android.intent.action.TTS_SERVICE" /></intent>
    </queries>

    <application""", 1)

if ".ReaderService" not in text:
    text = text.replace("</application>", """    <service
            android:name=".ReaderService"
            android:exported="false"
            android:foregroundServiceType="mediaPlayback" />
    </application>""", 1)

BOOK_TYPES = [
    "application/epub+zip", "application/pdf", "application/x-fictionbook+xml", "application/x-fictionbook",
    "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
    "text/plain", "text/markdown", "text/html", "application/octet-stream", "application/zip",
]
if "android.intent.action.SEND" not in text:
    data = "\n".join(f'                <data android:mimeType="{t}" />' for t in BOOK_TYPES)
    filters = f"""
            <intent-filter>
                <action android:name="android.intent.action.SEND" />
                <category android:name="android.intent.category.DEFAULT" />
{data}
            </intent-filter>
            <intent-filter>
                <action android:name="android.intent.action.VIEW" />
                <category android:name="android.intent.category.DEFAULT" />
                <category android:name="android.intent.category.BROWSABLE" />
                <data android:scheme="content" />
                <data android:scheme="file" />
{data}
            </intent-filter>
        </activity>"""
    # Only the main activity (the one with the LAUNCHER filter)
    m = re.search(r'(<activity\b[\s\S]*?android.intent.category.LAUNCHER[\s\S]*?)</activity>', text)
    if not m:
        raise SystemExit("MainActivity with LAUNCHER intent-filter not found in AndroidManifest.xml")
    text = text[:m.start()] + m.group(1) + filters.lstrip("\n").replace("            <intent-filter>", "            <intent-filter>", 1) + text[m.end():]

text = re.sub(r'android:launchMode="[^"]*"', 'android:launchMode="singleTask"', text)
MANIFEST.write_text(text, encoding="utf-8")

# ---- gradle
gradle = APP / "build.gradle"
g = gradle.read_text(encoding="utf-8")
if "build-overrides.gradle" not in g:
    g += "\napply from: '../../android-res/build-overrides.gradle'\n"
    gradle.write_text(g, encoding="utf-8")

# ---- window colours (no white flash before the web UI paints; dark in night mode)
for folder, colour in (("values", "#F4EFE7"), ("values-night", "#141210")):
    d = RES / folder
    d.mkdir(exist_ok=True)
    (d / "rz_colors.xml").write_text(
        f'<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <color name="rz_window">{colour}</color>\n</resources>\n',
        encoding="utf-8")
styles = RES / "values/styles.xml"
if styles.exists():
    s = styles.read_text(encoding="utf-8")
    if "@color/rz_window" not in s:
        s = re.sub(r'(<style\s+name="AppTheme\.NoActionBar"[^>]*>)',
                   r'\1\n        <item name="android:windowBackground">@color/rz_window</item>', s, count=1)
        styles.write_text(s, encoding="utf-8")

# ---- launcher icons
try:
    from PIL import Image
    src = Image.open("icons/icon-512.png").convert("RGBA")
    mask = Image.open("icons/icon-maskable-512.png").convert("RGBA")
    for size, dpi in [(48, "mdpi"), (72, "hdpi"), (96, "xhdpi"), (144, "xxhdpi"), (192, "xxxhdpi")]:
        d = RES / f"mipmap-{dpi}"
        d.mkdir(exist_ok=True)
        src.resize((size, size), Image.LANCZOS).save(d / "ic_launcher.png")
        src.resize((size, size), Image.LANCZOS).save(d / "ic_launcher_round.png")
    for size, dpi in [(108, "mdpi"), (162, "hdpi"), (216, "xhdpi"), (324, "xxhdpi"), (432, "xxxhdpi")]:
        d = RES / f"mipmap-{dpi}"
        mask.resize((size, size), Image.LANCZOS).save(d / "ic_launcher_foreground.png")
    colors = RES / "values/ic_launcher_background.xml"
    colors.write_text('<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <color name="ic_launcher_background">#1E1A16</color>\n</resources>\n', encoding="utf-8")
except ImportError:
    print("Pillow not installed — keeping the default Capacitor icons")

print("Android project patched for Разказвач")
